#!/usr/bin/env python3
"""Generate crates/gxtb/src/data/qvszp.rs (the q-vSZP basis as compiled-in tables) from
crates/gxtb/param/basisq, the basis file of the g-xTB 1.1.0 release (bit-identical in 2.0.1).

Usage: python3 crates/gxtb/scripts/make_qvszp_table.py [basisq] [output .rs]

The file is parsed as `params::QvszpParams::parse` reads it (blocks between `*` lines: a header
`Z k_cn k_q2 k_qcn`, shells `nprim l`, then `nprim` lines `alpha c0 c1`; Fortran `d` exponents
read as `e`), and every number is written with Python's shortest round-trip repr, so the Rust
literals are the parsed doubles bit for bit (`params::tests` checks the table against the parser).
"""
from __future__ import annotations
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CRATE = HERE.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else CRATE / "param/basisq"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else CRATE / "src/data/qvszp.rs"
MAX_ELEM = 103
L = {"s": 0, "p": 1, "d": 2, "f": 3, "g": 4}


def num(t: str) -> float:
    return float(t.replace("d", "e").replace("D", "e"))


def parse(text: str):
    lines = [l.strip() for l in text.splitlines() if l.strip()]
    elements: dict[int, tuple[list[float], list[tuple[int, list[list[float]]]]]] = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if line.startswith("*"):
            continue
        head = line.split()
        assert len(head) == 4, f"element header expected: {line!r}"
        z = int(head[0])
        assert 1 <= z <= MAX_ELEM, z
        k = [num(t) for t in head[1:]]
        shells = []
        while i < len(lines) and not lines[i].startswith("*"):
            nprim, l = lines[i].split()
            i += 1
            prims = []
            for _ in range(int(nprim)):
                prims.append([num(t) for t in lines[i].split()[:3]])
                i += 1
            shells.append((L[l.lower()], prims))
        elements[z] = (k, shells)
    return elements


def lit(x: float) -> str:
    return repr(x)


def main():
    elements = parse(SRC.read_text())
    out = [
        "// @generated by crates/gxtb/scripts/make_qvszp_table.py from crates/gxtb/param/basisq (the q-vSZP",
        "// basis of the g-xTB 1.1.0 release, grimme-lab/g-xtb, GPL-3.0; bit-identical in 2.0.1). Do not edit by hand.",
        "//! The q-vSZP basis as compiled-in tables (the `basisq` file, parsed at build time instead of at",
        "//! every process start): per element the effective-charge coefficients (k_cn, k_q2, k_qcn) and",
        "//! the shells (angular momentum, exponents, charge-independent and charge-linear coefficients).",
        "#![allow(clippy::excessive_precision, clippy::unreadable_literal)]",
        "",
        "/// One contracted shell: angular momentum, exponents, c0, c1.",
        "pub struct Shell {",
        "    pub l: usize,",
        "    pub alpha: &'static [f64],",
        "    pub c0: &'static [f64],",
        "    pub c1: &'static [f64],",
        "}",
        "",
        "/// One element: (k_cn, k_q2, k_qcn) and its shells in file order.",
        "pub struct Element {",
        "    pub k: [f64; 3],",
        "    pub shells: &'static [Shell],",
        "}",
        "",
        f"/// Indexed by atomic number (index 0 unused), H-Lr.",
        f"pub static ELEMENTS: [Option<Element>; {MAX_ELEM + 1}] = [",
        "    None,",
    ]
    for z in range(1, MAX_ELEM + 1):
        if z not in elements:
            out.append("    None,")
            continue
        k, shells = elements[z]
        out.append(f"    // Z = {z}")
        out.append(f"    Some(Element {{ k: [{', '.join(lit(x) for x in k)}], shells: &[")
        for l, prims in shells:
            cols = [[p[j] for p in prims] for j in range(3)]
            out.append(f"        Shell {{ l: {l},")
            for name, col in zip(("alpha", "c0", "c1"), cols):
                out.append(f"            {name}: &[{', '.join(lit(x) for x in col)}],")
            out.append("        },")
        out.append("    ] }),")
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT} ({len(elements)} elements)")


if __name__ == "__main__":
    main()
