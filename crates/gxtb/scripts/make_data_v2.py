#!/usr/bin/env python3
"""Generate crates/gxtb/src/data_v2.rs (g-xTB 2.0.1 parameter tables) from the parameter arrays
extracted from the 2.0.1 program (crates/gxtb/tests/reference_v2/params/*.json; the capture points are
listed in docs/gxtb-v2.0.1-spec.md, Appendix A).

Usage: python3 crates/gxtb/scripts/make_data_v2.py [params dir] [output .rs]

Every value is written with Python's shortest round-trip repr, so the Rust literals are the
program's doubles bit for bit. Tables the 2.0.1 program shares bit-identically with g-xTB 1.1.0
(q-vSZP basis, onsite exchange integrals Lambda0, Pauling EN, D3 vdW radii in Angstrom, the dftd4
reference polarizabilities, reference CNs, tanh charge function and pair weight factors) are taken
from src/data.rs / axtb-d4 instead; this script checks those identities where the JSON has the
arrays and stops if one fails.
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CRATE = HERE.parent
PARAMS = Path(sys.argv[1]) if len(sys.argv) > 1 else CRATE / "tests/reference_v2/params"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else CRATE / "src/data_v2.rs"


def load(name):
    return json.loads((PARAMS / f"{name}.json").read_text())


ham, cd, es, ex = load("hamiltonian"), load("classical_disp"), load("electrostatics_spin"), load("exchange")
G, A = ham["gxtb"], cd["arrays"]


def v1_table(name):
    src = (CRATE / "src/data.rs").read_text()
    m = re.search(name + r": \[(?:f64|i32); \d+\] = \[(.*?)\];", src, re.S)
    return [float(x) for x in m.group(1).replace("\n", " ").split(",") if x.strip()]


def same(a, b, what):
    if len(a) != len(b) or any(x != y for x, y in zip(a, b)):
        raise SystemExit(f"{what}: not identical to the v1.1 table")


def fmt(x):
    r = repr(float(x))
    return r if ("." in r or "e" in r or "inf" in r or "nan" in r) else r + ".0"


out = []
w = out.append


def per_atom(name, values, doc, ty="f64"):
    assert len(values) == 103, name
    w(f"/// {doc}")
    if ty == "usize":
        w(f"pub static {name}: [usize; 103] = [{', '.join(str(int(v)) for v in values)}];")
    else:
        w(f"pub static {name}: [f64; 103] = [")
        for k in range(0, 103, 6):
            w("    " + ", ".join(fmt(v) for v in values[k:k + 6]) + ",")
        w("];")
    w("")


def per_shell(name, rows, doc, n=4, ty="f64"):
    assert len(rows) == 103 and all(len(r) == n for r in rows), name
    w(f"/// {doc}")
    w(f"pub static {name}: [[{ty}; {n}]; 103] = [")
    for r in rows:
        w("    [" + ", ".join(str(int(v)) if ty == "usize" else fmt(v) for v in r) + "],")
    w("];")
    w("")


def flat(name, values, doc):
    w(f"/// {doc}")
    w(f"pub static {name}: [f64; {len(values)}] = [")
    for k in range(0, len(values), 6):
        w("    " + ", ".join(fmt(v) for v in values[k:k + 6]) + ",")
    w("];")
    w("")


# consistency checks between the JSON files (several arrays appear in more than one)
for key in ("pa_rvdw_scale",):
    assert G[key] == A[key]["values"] == es["arrays"][key] == ex[key], key
assert G["ps_reference_occ"] == es["arrays"]["ps_reference_occ"]
assert G["ps_tb1_zeffsh"] == es["arrays"]["ps_tb1_zeffsh"]
assert G["pa_cn_rcov"] == A["pa_cn_rcov"]["values"]
assert es["arrays"]["pa_hubbard_parameter"] == ex["pa_hubbard_parameter"]
assert G["pa_nshell"] == es["arrays"]["pa_nshell"] == ex["pa_nshell"]
# tables shared with v1.1 (bit-identical): onsite exchange integrals and dftd4 reference data
lidx = ex["onecxints_lidx"]
gm = v1_table("GMUNU")  # 9 per element: sp pp sd pd dd sf pf df ff
order = [(0, 1), (1, 1), (0, 2), (1, 2), (2, 2), (0, 3), (1, 3), (2, 3), (3, 3)]
for z in range(103):
    for k, (a, b) in enumerate(order):
        if ex["onecxints"][z][lidx[a][b] - 1] != gm[9 * z + k]:
            raise SystemExit(f"onecxints Z={z + 1} {a}{b} differs from v1.1 GMUNU")
    assert ex["onecxints"][z][0] == 0.0
for v2, v1 in (("d4srev_refcovcn", "D4_REFCOVCN"), ("d4srev_refcn", "D4_REFCN"), ("d4_tanh_params", "D4_TANH")):
    same(A[v2]["values"], v1_table(v1), v2)
wf, k3 = A["d4_weight_factors"]["values"], v1_table("K3_PAIR")
for i in range(103):
    for j in range(103):
        assert wf[i + 118 * j] == k3[i + 103 * j], "weight factors"

w("//! g-xTB 2.0.1 parameter tables, read bit-exactly from the 2.0.1 program's data symbols")
w("//! (module `tblite_xtb_gxtb` `pa_*`/`ps_*`/`pg_*` arrays, multicharge `eeqbc2025`, dftd4 `d4srev`).")
w("//!")
w("//! Generated by `crates/gxtb/scripts/make_data_v2.py` from `crates/gxtb/tests/reference_v2/params/*.json`;")
w("//! do not edit. Per-element arrays are indexed by Z - 1 (H = 0), per-shell arrays by")
w("//! `[Z - 1][shell]`, shells in q-vSZP basis order. The g-xTB 2.0.1 program and its parameters are")
w("//! GPL-3.0 (grimme-lab/g-xtb). Tables shared bit-identically with g-xTB 1.1.0 (q-vSZP basis,")
w("//! onsite exchange integrals, Pauling EN, D3 radii, dftd4 reference polarizabilities, reference")
w("//! CNs, tanh charge function, pair weight factors) are not repeated here (`crate::data`).")
w("")
w("#![allow(clippy::excessive_precision, clippy::unreadable_literal)]")
w("")

per_atom("NSHELL", G["pa_nshell"], "Shells per element (`pa_nshell`): the first `NSHELL` q-vSZP shells are used.", "usize")
per_atom("CN_RCOV", G["pa_cn_rcov"], "g-xTB CN radii (bohr, `pa_cn_rcov`): Rc = rcov_A + rcov_B.")
per_shell("H0_SELFENERGY", G["ps_h0_selfenergy"], "H0 self-energy (Eh, `ps_h0_selfenergy`).")
per_shell("H0_SELFENERGY_CN", G["ps_h0_selfenergy_cn"], "CN dependence of the self-energy (`ps_h0_selfenergy_cn`): se = se0 - se_cn CN.")
per_atom("H0_SHPOLY2", G["pa_h0_shpoly2"], "Element factor of the H0 distance polynomial (`pa_h0_shpoly2`).")
per_shell("H0_DIAT_SCALE", G["ps_h0_diat_scale"], "Diatomic-frame sigma, pi, delta scaling (`ps_h0_diat_scale`).", n=3)
per_shell("H0_EXP_SCALE", G["ps_h0_qvszp_exp_scal"], "Exponent scaling of the H0 basis (`ps_h0_qvszp_exp_scal`).")
per_atom("H0_K0_SCALE", G["pa_h0_qvszp_k0_scal"], "q_eff weight k0 of the H0 basis (`pa_h0_qvszp_k0_scal`).")
per_atom("H0_K2_SCALE", G["pa_h0_qvszp_k2_scal"], "q_eff weight k2 of the H0 basis (`pa_h0_qvszp_k2_scal`).")
per_atom("H0_K3_SCALE", G["pa_h0_qvszp_k3_scal"], "q_eff weight k3 of the H0 basis (`pa_h0_qvszp_k3_scal`).")
per_atom("H0_DIP_SCALE", G["pa_h0_dip_scale"], "Strength of the H0 anisotropy term (`pa_h0_dip_scale`).")
per_atom("RVDW_SCALE", G["pa_rvdw_scale"], "Scale of the shared van der Waals pair radius (`pa_rvdw_scale`).")
per_shell("ACP_LEVEL", G["ps_acp_level"], "ACP projector weights (Eh, `ps_acp_level`).")
per_shell("ACP_EXP", G["ps_acp_exp"], "ACP projector exponents (`ps_acp_exp`).")
per_atom("ACP_N", G["pa_nacp"], "Number of ACP projectors (`pa_nacp`).", "usize")
per_shell("ACP_L", G["pa_l_acp"], "Angular momenta of the ACP projectors (`pa_l_acp`).", ty="usize")
per_shell("REF_OCC", G["ps_reference_occ"], "Reference shell occupations n0_l (`ps_reference_occ`).")
per_shell("ZEFF_SHELL", G["ps_tb1_zeffsh"], "Aufbau valence electrons per shell Z_l (`ps_tb1_zeffsh`).")
per_atom("INCREMENT", A["pa_increment"]["values"], "Atomic energy increments (Eh, `pa_increment`).")
per_atom("REP_ALPHA", A["pa_rep_alpha"]["values"], "Repulsion exponent alpha0 (`pa_rep_alpha`).")
per_atom("REP_ZEFF", A["pa_rep_zeff"]["values"], "Repulsion effective charge Z0 (`pa_rep_zeff`).")
per_atom("REP_CN", A["pa_rep_cn"]["values"], "CN dependence of the repulsion exponent (`pa_rep_cn`).")
per_atom("REP_Q", A["pa_rep_q"]["values"], "Charge dependence of the repulsion charge (`pa_rep_q`).")
per_atom("REP_ROFFSET", A["pa_rep_roffset"]["values"], "Repulsion distance offset (bohr, `pa_rep_roffset`).")
per_atom("REP_K1", A["pa_rep_k1"]["values"], "Repulsion 1/R coefficient (bohr, `pa_rep_k1`).")
per_shell("IPEA", es["arrays"]["ps_tb1_ipea"], "First-order shell chemical potentials (`ps_tb1_ipea`).")
per_atom("IPEA_CN", es["arrays"]["pa_tb1_ipea_cn"], "CN dependence of the first-order term (`pa_tb1_ipea_cn`).")
per_shell("SHELL_HUBBARD", es["arrays"]["ps_tb2_shell_hubbard"], "Second-order shell Hubbard scaling (`ps_tb2_shell_hubbard`).")
per_atom("HUBBARD_CN", es["arrays"]["pa_tb2_hubbard_cn"], "CN dependence of the Hubbard parameters (`pa_tb2_hubbard_cn`).")
per_atom("HUBBARD", es["arrays"]["pa_hubbard_parameter"], "Element hardness (`pa_hubbard_parameter`).")
per_atom("HUBBARD_DERIV", es["arrays"]["pa_tb3_hubbard_derivs"], "Third-order Hubbard derivatives (`pa_tb3_hubbard_derivs`).")
per_atom("AES_DIP_SCALE", es["arrays"]["pa_aes_dip_scale"], "CN scaling of the AES atomic dipoles (`pa_aes_dip_scale`).")
per_atom("WLL_SCALE", es["arrays"]["pa_wll_scale"], "Spin-constant scaling k^W (`pa_wll_scale`).")
per_shell("SPIN_W0", es["arrays"]["spin_constants_wb97mv"], "Spin constants W0 (`spin_constants_wb97mv`): ss sp sd sf pp pd pf dd df ff.", n=10)
per_shell("FOCK_SHELL_HUBBARD", ex["ps_fock_shell_hubbard"], "Exchange shell Hubbard scaling (`ps_fock_shell_hubbard`).")
per_shell("FOCK_AVG_EXP", ex["ps_fock_avg_exp"], "Exponents xi of the exchange Hubbard averaging (`ps_fock_avg_exp`).")
per_atom("FOCK_CSCALE", ex["pa_fock_cscale"], "Bond-order correction strength (`pa_fock_cscale`).")
per_atom("FOCK_CRAD", ex["pa_fock_crad"], "Bond-order correction radius (bohr, `pa_fock_crad`).")
per_shell("ONECX", ex["onecxints"], "Onsite exchange integrals Lambda0 (`tblite_data_onecxints`): ss sp sd sf pp pd pf dd df ff.", n=10)

w("/// Shell factors of H0 (`pg_h0_kshell`), s p d f.")
w(f"pub const PG_H0_KSHELL: [f64; 4] = [{', '.join(fmt(x) for x in G['pg_h0_kshell'])}];")
w("/// Shell factors of the H0 distance polynomial (`pg_h0_shpoly2`).")
w(f"pub const PG_H0_SHPOLY2: [f64; 4] = [{', '.join(fmt(x) for x in G['pg_h0_shpoly2'])}];")
w("/// Third-order shell factors (`pg_tb3_kshell`).")
w(f"pub const PG_TB3_KSHELL: [f64; 4] = [{', '.join(fmt(x) for x in es['arrays']['pg_tb3_kshell'])}];")
w("/// Fourth-order shell factors (`pg_tb4_kshell`).")
w(f"pub const PG_TB4_KSHELL: [f64; 4] = [{', '.join(fmt(x) for x in es['arrays']['pg_tb4_kshell'])}];")
w("/// Off-diagonal factors G_l of the Mulliken exchange kernel (`pg_fock_offdiag_l`).")
w(f"pub const PG_FOCK_OFFDIAG: [f64; 4] = [{', '.join(fmt(x) for x in ex['pg_fock_offdiag_l'])}];")
w("/// Charge coefficients of the onsite exchange integrals (`pg_fock_kq`).")
w(f"pub const PG_FOCK_KQ: [f64; 4] = [{', '.join(fmt(x) for x in ex['pg_fock_kq'])}];")
w("")

eq = ham["eeqbc"]
for key, doc in (("chi", "electronegativity"), ("eta", "hardness"), ("rad", "charge width"), ("kcnchi", "CN scaling of chi"),
                 ("kqchi", "local-charge scaling of chi"), ("cap", "bond capacitance"), ("cov_radii", "CN radius (bohr, Rc = r_A + r_B)"),
                 ("avg_cn", "average CN"), ("rvdw_scale", "van der Waals radius scale")):
    per_atom("EEQBC_" + key.upper(), eq[key], f"EEQ-BC {doc} (multicharge `eeqbc2025` `eeqbc_{key}`, 2.0.1 build).")

flat("D4_REFQ", A["d4srev_gxtbq"]["values"], "revD4 reference charges (`d4srev` `gxtbq`, 7 x 118, reference index fastest).")
flat("D4_REFH", A["d4srev_gxtbh"]["values"], "revD4 charges of the hydrogen-subtracted secondary systems (`gxtbh`, 7 x 118).")
flat("D4_RCOV", A["d4_covalent_rad_d3"]["values"], "revD4 CN radii (bohr): 4/3 Pyykko radii x 1/0.529177210903 (`covalent_rad_d3`).")

OUT.write_text("\n".join(out))
print("wrote", OUT)
