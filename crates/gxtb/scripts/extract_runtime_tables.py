#!/usr/bin/env python3
"""Tabulate element functions of the g-xTB 1.1.0 program by calling them under gdb.

Usage: python3 crates/gxtb/scripts/extract_runtime_tables.py <g-xtb-1.1.0 dir> <output .rs>

`shellocc_ref_(iat, Z, occ)` returns the reference (average Mulliken) shell occupations of an
element; it is pure in Z (a table plus a linear interpolation for 58 < Z < 71). The program
stops at `scf_` for a water run, then the function is called for Z = 1..103 with gdb's
`call`. Needs gdb; the program's parameter files in the given directory.
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile

WATER = "3\nwater\nO 0 0 0.119262\nH 0 0.763239 -0.477047\nH 0 -0.763239 -0.477047\n"
BUF = 0x3B38B00  # the program's own output buffer of shellocc_ref_


def main():
    ref, target = os.path.abspath(sys.argv[1]), sys.argv[2]
    work = tempfile.mkdtemp()
    try:
        open(os.path.join(work, "mol.xyz"), "w").write(WATER)
        for a, b in (("gxtb_parameters", ".gxtb"), ("basisq", ".basisq"), ("eeq", ".eeq")):
            shutil.copy(os.path.join(ref, a), os.path.join(work, b))
        cmds = ["set pagination off", "break scf_", "run", "set $b = (int*)malloc(64)", "set $z = 1", "while $z <= 103",
                "  set $b[0] = 1", "  set $b[1] = $z"]
        cmds += [f"  set *(double*)0x{BUF + 8 * k:x} = 0" for k in range(4)]
        cmds += [f"  call (void)shellocc_ref_($b, $b+1, 0x{BUF:x})",
                 '  printf "OCC %d %.17g %.17g %.17g %.17g\\n", $z, ' + ", ".join(f"*(double*)0x{BUF + 8 * k:x}" for k in range(4)),
                 "  set $z = $z + 1", "end", "kill"]
        open(os.path.join(work, "gdb.cmd"), "w").write("\n".join(cmds) + "\n")
        env = dict(os.environ, OMP_NUM_THREADS="1", HOME=".")
        out = subprocess.run(["gdb", "-batch", "-x", "gdb.cmd", "--args", os.path.join(ref, "gxtb"), "-c", "mol.xyz"],
                             cwd=work, env=env, capture_output=True, text=True).stdout
    finally:
        shutil.rmtree(work)
    rows = [l.split()[1:] for l in out.splitlines() if l.startswith("OCC ")]
    assert len(rows) == 103, len(rows)
    lines = [
        "// @generated by crates/gxtb/scripts/extract_runtime_tables.py by calling functions of the",
        "// g-xTB 1.1.0 program (grimme-lab/g-xtb release v1.1.0, GPL-3.0) under gdb. Do not edit by hand.",
        "#![allow(clippy::excessive_precision, clippy::unreadable_literal)]",
        "",
        "/// Reference shell occupations per element (`shellocc_ref_`), shells in q-vSZP basis order;",
        "/// the reference populations of the charge-dependent terms (shell charge = reference - Mulliken",
        "/// population).",
        "pub static REF_SHELL_OCC: [[f64; 4]; 103] = [",
    ]
    for r in rows:
        lines.append("    [" + ", ".join(repr(float(x)) for x in r[1:5]) + "],")
    lines.append("];")
    open(target, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
