/// Masses (u) of `numbers` from `table`.
pub fn masses(numbers: &[usize], table: &[f64; 118]) -> Result<Vec<f64>> {
    numbers
        .iter()
        .map(|&z| {
            if (1..=118).contains(&z) {
                Ok(table[z - 1])
            } else {
                Err(Error::Input(format!("no atomic mass for element Z={z}")))
            }
        })
        .collect()
}
