#!/usr/bin/env python3
"""Generate Rust parameter tables from the Fortran reference sources.

Usage: python crates/axtb/scripts/gen_data.py <reference dir> <crates/axtb/src/param> [<crates/base/src>]

<reference dir> holds clones of tblite (as tblite-main), mctc-lib, multicharge, xtb 6.7.1
(the g-xTB 2.0.1 build, as xtb-gxtb) and grimme-lab/xtb at tag v6.8.0 (as xtb). The element
tables that every crate shares go to axtb-base (``elements.rs``; the third argument, by default
``crates/base/src`` of this script's checkout), the rest to axtb's ``param``. Fortran literals
are copied verbatim (no float round trip) and whole-array operations written in the
Fortran declaration (``* evtoau``, ``0.1_wp *``, ``1.0_wp +``, ``aatoau *``) become the
same single IEEE operation on every element, so each value is bit-identical to the
compiled Fortran parameter (gfortran folds parameter expressions with correct rounding
per operation).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

NUM = r"[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eEdD][-+]?\d+)?(?:_wp)?"


def literal(tok: str) -> str:
    tok = tok.strip().replace("_wp", "")
    tok = re.sub(r"[dD]", "e", tok)
    if re.fullmatch(r"[-+]?\d+", tok):
        return tok + ".0"
    if tok.startswith("."):
        tok = "0" + tok
    if tok.startswith("-."):
        tok = "-0" + tok[1:]
    if tok.startswith("+"):
        tok = tok[1:]
    m = re.fullmatch(r"([-]?\d+)(e[-+]?\d+)", tok)
    if m:
        tok = f"{m.group(1)}.0{m.group(2)}"
    if tok.endswith("."):
        tok += "0"
    tok = tok.replace(".e", ".0e")
    return tok


def operand(tok: str, idents: dict[str, str]) -> str:
    tok = tok.strip()
    if tok in idents:
        return idents[tok]
    return literal(tok)


def declaration(src: str, name: str) -> str:
    """Text of the right-hand side of ``name``'s parameter declaration, comments removed."""
    m = re.search(rf"parameter\s*::\s*{name}\s*(\([^)]*\))?\s*=", src, re.I)
    if m is None:
        raise KeyError(name)
    text = src[m.end():].replace("(/", "[").replace("/)", "]")
    lines, depth, out, seen = text.split("\n"), 0, [], False
    for line in lines:
        line = re.sub(r"!.*", "", line).replace("&", " ")
        out.append(line)
        depth += line.count("[") + line.count("(") - line.count("]") - line.count(")")
        seen = seen or "[" in line
        if depth <= 0 and seen:
            break
    return " ".join(out)


def single_precision(tok: str) -> bool:
    """A real literal without kind suffix or exponent letter d is default (single) precision."""
    tok = tok.strip()
    return "_wp" not in tok and re.search(r"[dD]", tok) is None and "." in tok


def extract(src: str, name: str, idents: dict[str, str]):
    """Return (values, wrap) where wrap(v) renders one element with the array operations."""
    body = declaration(src, name).strip()
    start, end = body.index("["), body.index("]")
    head, inner, tail = body[:start], body[start + 1:end], body[end + 1:]
    head = re.sub(r"reshape\s*\(\s*$", "", head.strip()).strip()
    pre = ""
    if head:
        m = re.fullmatch(rf"({NUM}|\w+)\s*([*+])", head)
        if m is None:
            raise ValueError(f"{name}: cannot parse prefix {head!r}")
        pre = f"{operand(m.group(1), idents)} {m.group(2)} "
    post = ""
    tail = re.sub(r",\s*shape\s*\(\s*\w+\s*\)", "", tail)
    tail = re.sub(r",\s*order\s*=\s*\[[^\]]*\]", "", tail).replace(")", " ").strip()
    if tail:
        m = re.fullmatch(rf"\*\s*({NUM}|\w+)", tail)
        if m is None:
            raise ValueError(f"{name}: cannot parse suffix {tail!r}")
        post = f" * {operand(m.group(1), idents)}"
    vals = []
    for v in inner.split(","):
        v = v.strip()
        if not v:
            continue
        lit = literal(v)
        vals.append(f"({lit}_f32 as f64)" if single_precision(v) else lit)

    def wrap(v: str) -> str:
        if pre and post:
            return f"({pre}{v}){post}"
        return f"{pre}{v}{post}"

    return vals, wrap


def emit(out: list[str], rust_name: str, vals, wrap, ncol=None, kind="f64", doc=None):
    if doc:
        out.append(f"/// {doc}")
    if kind == "usize":
        vals = [v.split(".")[0] for v in vals]
        wrap = lambda v: v  # noqa: E731
    if ncol is None:
        out.append(f"pub const {rust_name}: [{kind}; {len(vals)}] = [")
        per = 4 if kind == "f64" else 20
        for i in range(0, len(vals), per):
            out.append("    " + ", ".join(wrap(v) for v in vals[i:i + per]) + ",")
        out.append("];")
    else:
        assert len(vals) % ncol == 0, (rust_name, len(vals), ncol)
        n = len(vals) // ncol
        out.append(f"pub const {rust_name}: [[{kind}; {ncol}]; {n}] = [")
        for i in range(n):
            out.append("    [" + ", ".join(wrap(v) for v in vals[i * ncol:(i + 1) * ncol]) + "],")
        out.append("];")
    out.append("")


HEADER = [
    "// @generated by crates/axtb/scripts/gen_data.py from {src} (LGPL-3.0-or-later).",
    "// Do not edit by hand.",
    "#![allow(clippy::excessive_precision, clippy::unreadable_literal)]",
    "#![allow(clippy::approx_constant, clippy::neg_multiply)]",
    "",
]


def gen_gfn2(ref: Path, dst: Path) -> None:
    src = (ref / "tblite-main/src/tblite/xtb/gfn2.f90").read_text()
    out = [h.format(src="tblite xtb/gfn2.f90") for h in HEADER]
    out += ["/// eV to Hartree factor of the GFN2-xTB parametrization (1/27.21138505 eV, as xtb and",
            "/// tblite use). Part of the parametrization: the eV-valued parameters were fitted with it.",
            "pub const EVTOAU: f64 = 1.0 / 27.21138505;", ""]
    idents = {"evtoau": "EVTOAU"}
    for name, ncol in [
        ("rep_alpha", None), ("rep_zeff", None), ("hubbard_parameter", None),
        ("shell_hubbard", 3), ("p_hubbard_derivs", None), ("p_shpoly", 3), ("p_kcn", 3),
        ("reference_occ", 3), ("slater_exponent", 3), ("p_selfenergy", 3),
        ("p_dkernel", None), ("p_qkernel", None), ("p_vcn", None), ("p_rad", None),
    ]:
        vals, wrap = extract(src, name, idents)
        emit(out, name.upper(), vals, wrap, ncol)
    for name, ncol in [("nshell", None), ("ang_shell", 3), ("principal_quantum_number", 3),
                       ("number_of_primitives", 3)]:
        vals, wrap = extract(src, name, idents)
        emit(out, name.upper(), vals, wrap, ncol, kind="usize")
    (dst / "gfn2_data.rs").write_text("\n".join(out))


def gen_sto(ref: Path, dst: Path) -> None:
    src = (ref / "tblite-main/src/tblite/basis/slater.f90").read_text()
    out = [h.format(src="tblite basis/slater.f90") for h in HEADER]
    out.append("// STO-NG expansions, rows ordered 1s 2s 3s 4s 5s 2p 3p 4p 5p 3d 4d 5d 4f 5f 5g.")
    out.append("")
    vals, wrap = extract(src, "pAlpha1", {})
    emit(out, "P_ALPHA1", vals, wrap)
    for ng in range(2, 7):
        for kind in ("Alpha", "Coeff"):
            vals, wrap = extract(src, f"p{kind}{ng}", {})
            emit(out, f"P_{kind.upper()}{ng}", vals, wrap, ncol=ng)
    for name in ["pAlpha6s", "pCoeff6s", "pAlpha6p", "pCoeff6p"]:
        vals, wrap = extract(src, name, {})
        emit(out, re.sub(r"([a-z])([A-Z0-9])", r"\1_\2", name).upper(), vals, wrap)
    for name in ["pAlpha6sp", "pCoeff6sp_s", "pCoeff6sp_p"]:
        vals, wrap = extract(src, name, {})
        emit(out, re.sub(r"([a-z])([A-Z0-9])", r"\1_\2", name).upper(), vals, wrap, ncol=6)
    (dst / "sto_data.rs").write_text("\n".join(out))


def gen_elements(ref: Path, dst: Path) -> None:
    out = [h.format(src="mctc-lib data/{paulingen,covrad,atomicrad}.f90") for h in HEADER]
    out += ["use crate::units::reference::MCTC_AATOAU as AATOAU;", ""]
    src = (ref / "mctc-lib/src/mctc/data/paulingen.f90").read_text()
    vals, wrap = extract(src, "pauling_en", {})
    emit(out, "PAULING_EN", vals, wrap, doc="Pauling electronegativities (mctc-lib).")
    src = (ref / "mctc-lib/src/mctc/data/covrad.f90").read_text()
    vals, wrap = extract(src, "covalent_rad_2009", {"aatoau": "AATOAU"})
    emit(out, "COVALENT_RAD_2009", vals, wrap,
         doc="Covalent radii of Pyykko and Atsumi (metals -10%), bohr (mctc-lib).")
    src = (ref / "mctc-lib/src/mctc/data/atomicrad.f90").read_text()
    vals, wrap = extract(src, "atomic_rad", {"aatoau": "AATOAU"})
    emit(out, "ATOMIC_RAD", vals, wrap, doc="Atomic radii, bohr (mctc-lib).")
    # raw Ångström values for conventions that convert with a different bohr constant
    src = (ref / "mctc-lib/src/mctc/data/covrad.f90").read_text()
    vals, _ = extract(src, "covalent_rad_2009", {"aatoau": "AATOAU"})
    emit(out, "COVALENT_RAD_2009_AA", vals, lambda v: v, doc="Covalent radii of Pyykko and Atsumi (metals -10%), Ångström.")
    src = (ref / "mctc-lib/src/mctc/data/atomicrad.f90").read_text()
    vals, _ = extract(src, "atomic_rad", {"aatoau": "AATOAU"})
    emit(out, "ATOMIC_RAD_AA", vals, lambda v: v, doc="Atomic radii, Ångström (mctc-lib).")
    out += ["/// D3 covalent radii used for coordination numbers, bohr: 4/3 of the 2009 radii.",
            "pub const COVALENT_RAD_D3: [f64; 118] = {",
            "    let mut r = [0.0; 118];",
            "    let mut i = 0;",
            "    while i < 118 {",
            "        r[i] = 4.0 / 3.0 * COVALENT_RAD_2009[i];",
            "        i += 1;",
            "    }",
            "    r",
            "};", ""]
    (dst / "element_data.rs").write_text("\n".join(out))


def gen_base_elements(ref: Path, dst: Path) -> None:
    """The element tables of mctc-lib that the method crates share (``axtb_base::elements``;
    axtb, axtb-d4 and axtb-gfnff use or re-export them)."""
    out = [h.format(src="mctc-lib data/{paulingen,covrad}.f90 (Apache-2.0)") for h in HEADER]
    src = (ref / "mctc-lib/src/mctc/data/paulingen.f90").read_text()
    vals, wrap = extract(src, "pauling_en", {})
    emit(out, "PAULING_EN", vals, wrap, doc="Pauling electronegativities (mctc-lib).")
    src = (ref / "mctc-lib/src/mctc/data/covrad.f90").read_text()
    vals, _ = extract(src, "covalent_rad_2009", {"aatoau": "AATOAU"})
    emit(out, "COVALENT_RAD_2009_AA", vals, lambda v: v,
         doc="Covalent radii of Pyykko and Atsumi (metals -10%), Ångström (mctc-lib).")
    (dst / "elements.rs").write_text("\n".join(out))


def gen_xtb(ref: Path, dst: Path) -> None:
    """Tables exactly as the xtb program defines them, for 6.7.1 (`XTB671_*`: its own bohr
    constant, and the default-real (single precision) literals of its D4 coordination
    number) and 6.8.0 (`XTB_*`: mctc-lib's bohr constant, double-precision literals; only the
    operation order differs from mctc-lib's tables)."""
    old = ref / "xtb-gxtb/src"  # the g-xTB 2.0.1 build of xtb 6.7.1 (same tables as v6.7.1)
    new = ref / "xtb/src"       # grimme-lab/xtb at tag v6.8.0
    out = [h.format(src="xtb 6.7.1 and 6.8.0 src/param/*.f90, src/disp/ncoord.f90") for h in HEADER]
    out += ["use crate::units::reference::MCTC_AATOAU;", "",
            "/// xtb 6.7.1's bohr radius in Ångström (xtb src/mctc/convert.f90). Part of xtb 6.7.1's",
            "/// parametrization: its radius tables are converted with it. Not a physical constant to update.",
            "pub const XTB671_AUTOAA: f64 = 0.52917726;",
            "/// xtb 6.7.1's Ångström to bohr factor.",
            "pub const XTB671_AATOAU: f64 = 1.0 / XTB671_AUTOAA;",
            "/// xtb 6.8.0's Ångström to bohr factor: mctc-lib's (CODATA 2018 derived,",
            "/// `autoaa = 5.29177210904492434e-1_wp` in xtb src/mctc/convert.f90).",
            "pub const XTB_AATOAU: f64 = MCTC_AATOAU;", ""]
    for tag, x, aatoau, d4rad in (("XTB671", old, "XTB671_AATOAU", lambda v: f"4.0 / 3.0 * {v} / 0.52917726"),
                                  ("XTB", new, "XTB_AATOAU", lambda v: f"4.0 / 3.0 * {v} * XTB_AATOAU")):
        ver = "6.7.1" if tag == "XTB671" else "6.8.0"
        src = (x / "param/covalentradd3.f90").read_text()
        vals, _ = extract(src, "covalentRadD3", {})
        emit(out, f"{tag}_COVALENT_RAD_D3", vals, lambda v: f"{v} * {aatoau} * 4.0 / 3.0",
             doc=f"xtb {ver} covalentRadD3 (bohr): `[..] * aatoau * 4/3`.")
        src = (x / "param/atomicrad.f90").read_text()
        vals, _ = extract(src, "atomicRad", {})
        emit(out, f"{tag}_ATOMIC_RAD", vals, lambda v: f"{aatoau} * {v}", doc=f"xtb {ver} atomicRad (bohr).")
        src = (x / "param/paulingen.f90").read_text()
        vals, wrap = extract(src, "paulingEN", {})
        emit(out, f"{tag}_PAULING_EN", vals, wrap, doc=f"xtb {ver} paulingEN.")
        src = (x / "disp/ncoord.f90").read_text()
        vals, _ = extract(src, "rad", {})
        lit = "from default-real literals" if tag == "XTB671" else "double precision"
        emit(out, f"{tag}_D4_RCOV", vals, d4rad,
             doc=f"Covalent radii (bohr) of xtb {ver}'s D4 coordination number (`ncoord_d4`), {lit}.")
        vals, wrap = extract(src, "en", {})
        emit(out, f"{tag}_D4_EN", vals, wrap, doc=f"Electronegativities of xtb {ver}'s D4 coordination number, {lit}.")
    (dst / "xtb_data.rs").write_text("\n".join(out))


def gen_eeq(ref: Path, dst: Path) -> None:
    src = (ref / "multicharge/src/multicharge/param/eeq2019.f90").read_text()
    out = [h.format(src="multicharge param/eeq2019.f90 (Apache-2.0)") for h in HEADER]
    for name in ["eeq_chi", "eeq_eta", "eeq_kcnchi", "eeq_rad"]:
        vals, wrap = extract(src, name, {})
        emit(out, name.upper(), vals, wrap)
    (dst / "eeq_data.rs").write_text("\n".join(out))


def main() -> None:
    ref, dst = Path(sys.argv[1]), Path(sys.argv[2])
    base = Path(sys.argv[3]) if len(sys.argv) > 3 else Path(__file__).resolve().parents[2] / "base/src"
    gen_base_elements(ref, base)
    gen_gfn2(ref, dst)
    gen_sto(ref, dst)
    gen_elements(ref, dst)
    gen_xtb(ref, dst)
    gen_eeq(ref, dst)


if __name__ == "__main__":
    main()
