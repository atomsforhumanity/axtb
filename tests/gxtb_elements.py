#!/usr/bin/env python3
"""g-xTB element coverage: axtb in program conventions against both g-xTB programs, H-Lr.

Every element 1-103 in one small molecule (the GFN2 reference matrix's `elements` category,
with high-spin f^n states because g-xTB treats the f shells explicitly; actinides 87-103 added
the same way), plus a second environment for many elements (aqua and ammine ions, halides,
oxides, radicals; closed and open shells). All geometries are generated by
tests/reference_matrix/structures.py: no structure comes from a research project.

For every molecule and version:

- g-xTB 2.0.1 (`xtb mol.xyz --gxtb --norestart --chrg Q [--uhf U] --grad`, default and
  `--acc 0.0001`) against `axtb --method gxtb-v2.0.1 --conventions gxtb --grad` [`--acc
  0.0001`]: total energy, SCF iterations, convergence, the printed terms (core increments,
  three-body dispersion, electronic energy, 14 digits) and the analytic gradients.
- g-xTB v1.1 (the 1.1.0 program, `gxtb -c mol.xyz` and `-grad -symthr 0`) against `axtb
  --method gxtb-v1.1 --conventions gxtb`: total energy (`energy` file, 14 decimals), SCF
  iterations, convergence (`NOT_CONVERGED`), the printed terms (8 decimals). The program's
  gradient is numerical (central differences with its default SCF thresholds, noise ~2e-5
  Eh/bohr), so axtb's analytic gradient is checked against five-point finite differences of
  tightly converged axtb energies (both conventions); the program's gradient is compared only
  at its noise level. Elements without v1.1 parameters (Z = 59-69, 90, 91, 93-103: absent from
  the public parameter file, spec §3.1) are run as well; axtb refuses them.

Status per molecule and version (the classification of the existing tests):

  ok                  same energy (≤ 1e-9 Eh), iterations and printed terms; gradients agree
  rounding-sensitive  same converged state, but the SCF path depends on round-off (e.g. an
                      exactly degenerate, partially filled HOMO set in an early iteration,
                      whose occupied subspace each eigensolver picks differently)
  another-solution    both converge, to different states (restart diagnosis in `note`)
  both-fail           neither SCF converges (or both refuse the input)
  unparametrized      v1.1 element without parameters (both refuse or the program fails)
  program-gradient    (2.0.1) energies agree, the program's analytic gradient does not: it
                      agrees after a rotation of the input, while axtb's gradient does not
                      change (bonds along a coordinate axis; finite differences of the
                      program's energies follow axtb)
  real-difference     anything else (a bug)

A mismatch is diagnosed by running both programs on a rotated copy of the molecule (a pure
change of round-off): it is rounding-sensitive if it disappears there or if axtb's own result
moves as much under the rotation.

    python tests/gxtb_elements.py [--versions 2.0.1,1.1] [--only ID,...] [--jobs 6]
                                  [--no-fd] [--out bench/results/gxtb_elements.json]

Programs (tests/programs.py): the g-xTB 2.0.1 build of xtb (`$AXTB_GXTB2`) for version 2.0.1,
the g-xTB 1.1.0 program (`$AXTB_GXTB11_DIR`) for 1.1; a version whose program is not there is
skipped. All runs with OMP_NUM_THREADS=1. Known classifications that need a manual diagnosis are in `KNOWN`.
"""

