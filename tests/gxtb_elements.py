def run_xtb2(m, wd: Path, *extra) -> dict:
    wd.mkdir(parents=True, exist_ok=True)
    for f in ("xtbrestart", "gradient", "energy", "charges", "NOT_CONVERGED"):
        (wd / f).unlink(missing_ok=True)
    (wd / "mol.xyz").write_text(xyz_text(m))
    env = dict(os.environ, OMP_NUM_THREADS="1", MKL_NUM_THREADS="1", OMP_STACKSIZE="1G", HOME=str(wd))
    cmd = [XTB2, "mol.xyz", "--gxtb", "--norestart", "--chrg", str(m["charge"])]
    if m["uhf"]:
        cmd += ["--uhf", str(m["uhf"])]
    p = subprocess.run(cmd + list(extra), cwd=wd, env=env, capture_output=True, text=True, timeout=3600)
    out = p.stdout + p.stderr
    (wd / "program.out").write_text(out)
    r = {"returncode": p.returncode}
    cyc = re.findall(r"^\s+(\d+)\s+(-?\d+\.\d+)\s+(-?\d\.\d+E[+-]\d+)\s+(-?\d\.\d+E[+-]\d+)\s*$", out, re.M)
    r["iterations"] = len(cyc)
    for lab, key in (("total energy", "energy"), ("electronic energy", "electronic"),
                     ("core increment energy", "increments"), ("dispersion energy", "dispersion_three_body")):
        mm = re.search(r"^" + lab + r"\s+(-?\d\.\d+E[+-]\d+)", out, re.M)
        if mm:
            r[key] = float(mm.group(1))
    r["converged"] = p.returncode == 0 and "energy" in r and "SCF not converged" not in out \
        and "not converged" not in out.lower()
    if not r["converged"]:
        r["error"] = "\n".join(l for l in out.splitlines() if "error" in l.lower() or "converge" in l.lower())[-300:] \
            or out[-300:]
    if (wd / "gradient").exists() and r["converged"]:
        lines = (wd / "gradient").read_text().splitlines()
        rows = [l.split() for l in lines[2:] if not l.startswith("$")]
        nat = len(m["numbers"])
        r["gradient"] = [[float(x.replace("D", "E")) for x in row] for row in rows[nat:2 * nat]]
    return r


V11_TERMS = {"ES1 (charge SIE)": "es1", "ES2+3": "es2_3", "ES multipole": "es_multipole",
             "Ex (Mulliken)": "exchange", "Espinpol": "spin_polarization", "electronic": "electronic",
             "atomic core increments": "increments", "dispersion": "dispersion", "nuclear repulsion": "repulsion"}


def run_gxtb11(m, wd: Path, *extra) -> dict:
    wd.mkdir(parents=True, exist_ok=True)
    for f in (".gxtb", ".basisq", ".eeq"):
        shutil.copy(GXTB11_DIR / f, wd / f)
    for f in ("gxtbrestart", "energy", "gradient", "NOT_CONVERGED", ".UHF"):
        (wd / f).unlink(missing_ok=True)
    (wd / "mol.xyz").write_text(xyz_text(m))
    (wd / ".CHRG").write_text(f"{m['charge']}\n")
    if m["uhf"]:  # any .UHF file, even 0, makes the 1.1.0 program unrestricted
        (wd / ".UHF").write_text(f"{m['uhf']}\n")
    env = dict(os.environ, OMP_NUM_THREADS="1", MKL_NUM_THREADS="1", HOME=".")
    try:
        p = subprocess.run([str(GXTB11_DIR / "gxtb"), "-c", "mol.xyz", *extra], cwd=wd, env=env, capture_output=True,
                           text=True, timeout=1800)
    except subprocess.TimeoutExpired:
        return {"converged": False, "error": "timeout (1800 s)"}
    out = p.stdout + p.stderr
    (wd / "program.out").write_text(out)
    r = {"returncode": p.returncode}
    mm = re.search(r"^\s*(\d+)\s+scf iterations", out, re.M)
    r["iterations"] = int(mm.group(1)) if mm else None
    terms = {}
    for lab, key in V11_TERMS.items():
        mm = re.search(r"^" + re.escape(lab) + r"\s+:\s+(-?\d+\.\d+)", out, re.M)
        if mm:
            terms[key] = float(mm.group(1))
    r["terms"] = terms
    if (wd / "energy").exists():
        r["energy"] = float((wd / "energy").read_text().split()[2])
    failed = (wd / "NOT_CONVERGED").exists() or "no SCF convergence" in out
    r["converged"] = p.returncode == 0 and not failed and "energy" in r and r["iterations"] is not None \
        and all(math.isfinite(v) for v in terms.values())
    if not r["converged"]:
        r["error"] = ("no SCF convergence" if failed else f"returncode {p.returncode}: ") + \
            ("" if failed else out.strip()[-200:])
    if "-grad" in extra and (wd / "gradient").exists() and r["converged"]:
        lines = (wd / "gradient").read_text().splitlines()
        rows = [l.split() for l in lines[2:] if not l.startswith("$")]
        nat = len(m["numbers"])
        r["gradient"] = [[float(x.replace("D", "E")) for x in row] for row in rows[nat:2 * nat]]
    return r


def run_axtb_file(m, wd: Path, method: str, conv: str, *extra) -> dict:
    wd.mkdir(parents=True, exist_ok=True)
    (wd / "mol.xyz").write_text(xyz_text(m))
    cmd = [AXTB, str(wd / "mol.xyz"), "--method", method, "--conventions", conv, "--chrg", str(m["charge"]),
           "--uhf", str(m["uhf"]), *extra]
    p = subprocess.run(cmd, capture_output=True, text=True, timeout=3600)
    if p.returncode != 0:
        return {"error": p.stderr.strip()[-300:]}
    return json.loads(p.stdout)


def axtb_energy(m, positions, method, conv, acc) -> float:
    req = {"numbers": m["numbers"], "positions": positions, "charge": m["charge"], "uhf": m["uhf"],
           "method": method, "conventions": conv, "accuracy": acc, "max_iter": 1000}
    p = subprocess.run([AXTB, "--json"], input=json.dumps(req), capture_output=True, text=True, timeout=3600)
    if p.returncode != 0:
        raise RuntimeError((p.stderr + p.stdout).strip()[-300:])
    return json.loads(p.stdout)["energy"]


def fd_check(m, method, conv, pool, steps=(1e-3, 4e-3)):
    """Analytic gradient vs five-point differences of energies, both with tight SCF thresholds
    (accuracy 1e-7: 1e-15 Eh and RMS density 2e-12, open shells 4e-14 and 5e-12; 1e-6 if that
    does not converge; the program conventions' energies are first order in the SCF error).
    Differences at h = 1e-3 bohr; above 1e-8 Eh/bohr also at 4e-3. An error that scales as 1/h is
    a step in the energy (a primitive pair crossing the integral screening), not a gradient
    error: reported as `step_Eh`. `max_dgrad` is the smaller maximum of the two steps."""
    err = ""
    x0 = np.array(m["positions"])

    def differences(g, h, acc):
        jobs = []
        for a in range(len(x0)):
            for k in range(3):
                for s in (-2, -1, 1, 2):
                    x = x0.copy()
                    x[a, k] += s * h
                    jobs.append(((a, k, s), x.tolist()))
        es = dict(zip([j[0] for j in jobs], pool.map(lambda j: axtb_energy(m, j[1], method, conv, acc), jobs)))
        fd = np.zeros_like(g)
        for a in range(len(x0)):
            for k in range(3):
                e = {s: es[(a, k, s)] for s in (-2, -1, 1, 2)}
                fd[a, k] = (e[-2] - 8 * e[-1] + 8 * e[1] - e[2]) / (12 * h)
        return np.abs(g - fd).max()

    for acc in (1e-7, 1e-6):
        req = {"numbers": m["numbers"], "positions": m["positions"], "charge": m["charge"], "uhf": m["uhf"],
               "method": method, "conventions": conv, "accuracy": acc, "gradient": True, "max_iter": 1000}
        p = subprocess.run([AXTB, "--json"], input=json.dumps(req), capture_output=True, text=True, timeout=3600)
        if p.returncode != 0:
            err = p.stderr.strip()[-300:]
            continue
        g = np.array(json.loads(p.stdout)["gradient"])
        try:
            errs = {steps[0]: differences(g, steps[0], acc)}
            if errs[steps[0]] > TOL_G:
                errs[steps[1]] = differences(g, steps[1], acc)
        except RuntimeError as e:
            err = f"displaced geometry: {e}"
            continue
        out = {"accuracy": acc, "max_dgrad": float(min(errs.values())),
               "max_dgrad_by_step": {f"{h:g}": float(v) for h, v in errs.items()}, "max_grad": float(np.abs(g).max())}
        if len(errs) == 2:
            e1, e2 = errs[steps[0]], errs[steps[1]]
            ratio = steps[1] / steps[0]
            if e2 > TOL_G and 0.7 * ratio < e1 / e2 < 1.4 * ratio:
                out["step_Eh"] = float(e1 * 12 * steps[0] / 8)
        return out
    return {"error": err}


def maxdiff(a, b) -> float:
    return float(np.abs(np.array(a) - np.array(b)).max())


