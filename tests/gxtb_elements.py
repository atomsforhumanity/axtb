def f_unpaired(n: int) -> int:
    return min(n, 14 - n)


def _primary():
    """(element, label, builder, charge, uhf): one molecule per element 1-103."""
    out = []
    for z in range(1, 87):
        sym = S.SYMBOLS[z - 1]
        build, charge, uhf, label = M.ELEMENT_MOLECULES[sym]
        if sym in LN:  # LnCl3 with the f^n high-spin state
            uhf = f_unpaired(LN.index(sym))
            label = f"{sym}Cl3" + (f" (f{LN.index(sym)}, 2S+1 = {uhf + 1})" if uhf else "")
        out.append((sym, label, build, charge, uhf))
    act = [
        ("Fr", "FrH", lambda: S.hydride("Fr", 1), 0, 0),
        ("Ra", "RaH2", lambda: S.hydride("Ra", 2), 0, 0),
        ("Ac", "AcCl3", lambda: S.star("Ac", ["Cl"] * 3, "trigonal"), 0, 0),
        ("Th", "ThCl4", lambda: S.star("Th", ["Cl"] * 4, "tetrahedral"), 0, 0),
        ("Pa", "PaCl5", lambda: S.star("Pa", ["Cl"] * 5, "tbp"), 0, 0),
        ("U", "UF6", lambda: S.star("U", ["F"] * 6, "octahedral", r=2.00), 0, 0),
        ("Np", "NpF6 (f1)", lambda: S.star("Np", ["F"] * 6, "octahedral", r=1.98), 0, 1),
        ("Pu", "PuF6 (f2)", lambda: S.star("Pu", ["F"] * 6, "octahedral", r=1.97), 0, 2),
    ]
    for k, sym in enumerate("Am Cm Bk Cf Es Fm Md".split()):
        nf = 6 + k
        act.append((sym, f"{sym}Cl3 (f{nf})", (lambda sym=sym: S.star(sym, ["Cl"] * 3, "trigonal")), 0, f_unpaired(nf)))
    act += [
        ("No", "NoCl2 (f14)", lambda: S.star("No", ["Cl"] * 2, "linear"), 0, 0),
        ("Lr", "LrCl3", lambda: S.star("Lr", ["Cl"] * 3, "trigonal"), 0, 0),
    ]
    return out + act


