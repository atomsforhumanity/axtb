# elements and environments the 19 + 36 reference molecules did not cover: one per block and
# row, open shells, the early DIIS switch (H2), f elements without v1.1 parameters (2.0.1 only)
REFERENCE_IDS = ["001-H", "004-Be", "012-Mg", "021-Sc", "025-Mn", "027-Co", "036-Kr", "037-Rb", "039-Y", "042-Mo",
                 "044-Ru", "046-Pd", "055-Cs", "072-Hf", "076-Os", "077-Ir", "086-Rn", "087-Fr", "088-Ra", "089-Ac",
                 "091-Pa", "059-Pr", "066-Dy", "096-Cm", "102-No", "103-Lr", "027-Co-2", "025-Mn-2", "006-C-3"]
# 2.0.1 (crates/gxtb/tests/reference_v2/elements via v2_element_cases.py): the same without MnO4-
# and CsH, whose tight program gradients agree only to 2.3e-10 and 1.4e-10 Eh/bohr (the unit
# test's limit is 1e-10)
REFERENCE_IDS_V2 = [c for c in REFERENCE_IDS if c not in ("025-Mn", "055-Cs")]
GD_AQUA = "064-Gd-2"  # the 2.0.1 program's gradient for bonds along a coordinate axis


def write_reference(results: Path):
    """Representative ok cases of the survey into the reference sets: v1.1 total energies and
    iterations into crates/gxtb/tests/reference_extra.json; the 2.0.1 ones are generated by
    crates/gxtb/scripts/make_reference_v2.py (v2_element_cases.py takes REFERENCE_IDS from
    here); and the program energies around [Gd(H2O)6]3+ for its gradient error."""
    rows = {(r["version"], r["id"]): r for r in json.loads(results.read_text())["rows"]}
    mols = {m["id"]: m for m in molecules()}
    path = ROOT / "crates/gxtb/tests/reference_extra.json"
    doc = json.loads(path.read_text())
    keep = [x for x in doc["molecules"] if x.get("source") != "tests/gxtb_elements.py"]
    for cid in REFERENCE_IDS:
        r = rows.get(("1.1", cid))
        if r is None or r["status"] != "ok":
            continue
        m = mols[cid]
        keep.append({"name": f"{cid} {m['label']}", "xyz": xyz_text(m), "charge": m["charge"], "uhf": m["uhf"],
                     "total_energy": r["program"]["energy"], "scf_iterations": r["program"]["iterations"],
                     "source": "tests/gxtb_elements.py"})
    doc["molecules"] = keep
    doc["note"] = ("geometries from tests/structures of the axtb repository and (source tests/gxtb_elements.py) "
                   "generated element molecules; total energy from the program's `energy` file")
    path.write_text(json.dumps(doc, indent=1) + "\n")
    print("wrote", path, len(keep), "molecules")
    # [Gd(H2O)6]3+: the program's tight energies at +-h, +-2h along the coordinates where its
    # analytic gradient is off (atoms 0, 13, 16, y), and its tight gradient
    m = mols[GD_AQUA]
    h = 1e-3
    out = {"molecule": m["label"], "xyz": xyz_text(m), "charge": m["charge"], "uhf": m["uhf"], "step_bohr": h,
           "program": "g-xTB 2.0.1 (xtb 6.7.1 --gxtb --acc 0.0001)", "displaced": []}
    with tempfile.TemporaryDirectory(dir=os.environ.get("AXTB_SCRATCH")) as tmp:
        g = run_xtb2(m, Path(tmp) / "g", "--grad", "--acc", "0.0001")
        out["energy"], out["gradient"] = g["energy"], g["gradient"]
        for atom in (0, 13, 16):
            e = {}
            for s in (-2, -1, 1, 2):
                x = np.array(m["positions"])
                x[atom, 1] += s * h
                r = run_xtb2({**m, "positions": x.tolist()}, Path(tmp) / f"{atom}{s}", "--acc", "0.0001")
                e[s] = r["energy"]
            out["displaced"].append({"atom": atom, "axis": 1, "energies": [e[-2], e[-1], e[1], e[2]]})
    p = ROOT / "crates/gxtb/tests/reference_elements/gd_aqua_v2_gradient.json"
    p.write_text(json.dumps(out, indent=1) + "\n")
    print("wrote", p)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--versions", default="2.0.1,1.1")
    ap.add_argument("--only", default="")
    ap.add_argument("--jobs", type=int, default=6)
    ap.add_argument("--no-fd", action="store_true")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--write-reference", action="store_true")
    ap.add_argument("--out", type=Path, default=ROOT / "bench/results/gxtb_elements.json")
    a = ap.parse_args()
    if a.write_reference:
        write_reference(a.out)
        return 0
    mols = molecules()
    if a.only:
        sel = a.only.split(",")
        mols = [m for m in mols if any(s == m["id"] or s == m["element"] for s in sel)]
    if a.list:
        for m in mols:
            print(m["id"], m["label"], m["charge"], m["uhf"], len(m["numbers"]))
        return 0
    versions = [v for v in a.versions.split(",") if programs.note_skip(f"version {v}", VERSION_VAR[v])]
    if not versions:
        programs.skip(programs.reason(*(VERSION_VAR[v] for v in a.versions.split(","))))
    rows = []
    with tempfile.TemporaryDirectory(dir=os.environ.get("AXTB_SCRATCH")) as tmp, \
            ThreadPoolExecutor(a.jobs) as pool, ThreadPoolExecutor(a.jobs) as fdpool:
        futs = [pool.submit(worker, v, m, Path(tmp), fdpool, not a.no_fd) for v in versions for m in mols]
        for f in futs:
            r = f.result()
            rows.append(r)
            print(f"{r['version']:6} {r['id']:10} {r['label'][:28]:28} {r['status']:18} dE {r.get('dE', float('nan')):9.1e} "
                  f"it {r.get('iterations')} {r['note'][:90]}", flush=True)
    merged = rows
    if a.only and a.out.exists():  # keep the rows not run
        old = json.loads(a.out.read_text())["rows"]
        done = {(r["version"], r["id"]) for r in rows}
        merged = [r for r in old if (r["version"], r["id"]) not in done] + rows
    merged.sort(key=lambda r: (r["version"], r["Z"], r["id"]))
    summary = summarize(merged)
    a.out.write_text(json.dumps({
        "programs": {"2.0.1": "g-xTB 2.0.1 (grimme-lab/g-xtb 2.0.1: xtb 6.7.1 --gxtb)",
                     "1.1": "g-xTB 1.1.0 (grimme-lab/g-xtb v1.1.0)"},
        "axtb": "conventions=\"gxtb\" (program conventions); dE_default: conventions=\"axtb\"",
        "tolerances": {"dE": TOL_E, "dG": TOL_G, "printed_terms": TOL_T},
        "dG": {"2.0.1": "axtb's analytic gradient vs the program's (default thresholds), Eh/bohr",
               "1.1": "axtb's analytic gradient (program conventions) vs five-point differences of tight axtb "
                      "energies, Eh/bohr (the program's own gradient is numerical)"},
        "summary": summary, "table": report_table(merged), "rows": merged}, indent=1))
    print(json.dumps(summary, indent=1))
    print("wrote", a.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
