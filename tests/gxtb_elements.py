TOL_E = 1e-9
TOL_G = 1e-8
TOL_T = {"1.1": 5.1e-9, "2.0.1": 1e-9}  # printed terms: 8 decimals (v1.1), 14 digits (2.0.1)
# Perturbations of the input for the diagnosis of mismatches. SHIFT (a translation and the atoms
# in reverse order) changes only the round-off. ROT (a rotation) also tests orientation: g-xTB
# 1.1.0's own results depend on the orientation (its onsite-exchange Fock matrix is not rotation
# covariant, spec §4.18), so ROT is used only for gradient mismatches of 2.0.1.
SHIFT = {"rot": np.eye(3), "shift": np.array([0.31, -0.17, 0.23]), "reverse": True}
ROT = {"rot": np.linalg.qr(np.random.default_rng(7).normal(size=(3, 3)))[0], "shift": np.zeros(3), "reverse": False}
# cases a manual diagnosis classified; (version, id) -> (status, note)
KNOWN: dict[tuple[str, str], tuple[str, str]] = {
    ("2.0.1", "100-Fm"): ("rounding-sensitive",
                          "FmCl3 (f11): the default-threshold gradient differs from the program's by 1.3e-6 to 1.8e-6 "
                          "Eh/bohr with the same energy and iterations, and axtb's own gradient moves by 1.2e-7 to "
                          "3.8e-6 under the shifted copy or a change of round-off"),
}
# tight-threshold classifications decided by more than the shifted copy
KNOWN_TIGHT: dict[tuple[str, str], tuple[str, str]] = {}


def transformed(m, tr):
    x = np.array(m["positions"]) @ tr["rot"].T + tr["shift"]
    order = list(range(len(x)))[::-1] if tr["reverse"] else list(range(len(x)))
    return {**m, "numbers": [m["numbers"][i] for i in order], "positions": x[order].tolist()}, order


def measure(version: str, m, wd: Path, tr=None) -> dict:
    """The program and axtb (program conventions, default thresholds) on one molecule; with
    `tr`, on the transformed molecule, gradients transformed back."""
    mm, order = (m, None) if tr is None else transformed(m, tr)
    if version == "2.0.1":
        prog = run_xtb2(mm, wd / "prog", "--grad")
        ax = run_axtb_file(mm, wd / "ax", "gxtb-v2.0.1", "gxtb", "--grad")
        pterms = {k: prog[k] for k in ("electronic", "increments", "dispersion_three_body") if k in prog}
        aterms = {k: ax["terms"][k] for k in pterms} if "terms" in ax else {}
    else:
        prog = run_gxtb11(mm, wd / "prog")
        ax = run_axtb_file(mm, wd / "ax", "gxtb-v1.1", "gxtb", "--grad")
        pterms = prog.get("terms", {})
        t = ax.get("terms")
        # printed "Ex (Mulliken)" is the Mulliken exchange alone, "dispersion" the two-body revD4
        aterms = {} if t is None else {
            "es1": t["es1"], "es2_3": t["es2_3"], "es_multipole": t["es_multipole"], "exchange": t["exchange_mulliken"],
            "spin_polarization": t["spin_polarization"], "electronic": t["electronic"], "increments": t["increments"],
            "dispersion": t["dispersion"], "repulsion": t["repulsion"]}
    out = {"prog": {"energy": prog.get("energy"), "iterations": prog.get("iterations"), "converged": prog["converged"],
                    "error": prog.get("error"), "terms": pterms, "gradient": prog.get("gradient")},
           "ax": {"energy": ax.get("energy"), "iterations": ax.get("iterations"), "converged": "error" not in ax,
                  "error": ax.get("error"), "terms": aterms, "gradient": ax.get("gradient")}}
    if tr is not None:
        for side in out.values():
            if side["gradient"] is not None:
                g = np.array(side["gradient"]) @ tr["rot"]
                back = np.zeros_like(g)
                back[order] = g
                side["gradient"] = back.tolist()
    return out


def metrics(a: dict, b: dict) -> dict:
    """a - b for two results (both converged)."""
    out = {"dE": a["energy"] - b["energy"], "iterations": [a["iterations"], b["iterations"]],
           "dterms": {k: a["terms"][k] - v for k, v in b["terms"].items() if k in a["terms"]}}
    if a["gradient"] is not None and b["gradient"] is not None:
        out["dG"] = maxdiff(a["gradient"], b["gradient"])
    return out


def issues(version: str, met: dict, gradient: bool) -> list[str]:
    out = []
    if abs(met["dE"]) > TOL_E:
        out.append(f"dE {met['dE']:.1e}")
    if met["iterations"][0] != met["iterations"][1]:
        out.append(f"iterations {met['iterations'][0]} vs {met['iterations'][1]}")
    bad = {k: v for k, v in met["dterms"].items() if abs(v) > TOL_T[version]}
    if bad:
        out.append("terms " + ", ".join(f"{k} {v:.1e}" for k, v in bad.items()))
    if gradient and met.get("dG", 0) > TOL_G:
        out.append(f"dG {met['dG']:.1e}")
    return out


def describe(met) -> str:
    t = max((abs(v) for v in met["dterms"].values()), default=0.0)
    return (f"dE {met['dE']:.1e}, iterations {met['iterations'][0]} vs {met['iterations'][1]}, terms {t:.1e}"
            + (f", dG {met['dG']:.1e}" if "dG" in met else ""))


def diagnose(version: str, m, wd: Path, r0: dict, met0: dict, found: list[str]) -> tuple[str, str]:
    """A mismatch: run both programs on the shifted molecule (translation, atoms reversed: a
    change of round-off only). Rounding-sensitive if the mismatch disappears there or if axtb's
    own result moves as much (10 %) or changes its iteration count. A 2.0.1 gradient mismatch
    that survives is tested with a rotation: the program's if both agree on the rotated molecule
    while axtb's gradient does not change."""
    gradient = version == "2.0.1"
    r1 = measure(version, m, wd / "shift", SHIFT)
    if not (r1["prog"]["converged"] and r1["ax"]["converged"]):
        status = "rounding-sensitive" if r1["prog"]["converged"] != r1["ax"]["converged"] else "real-difference"
        return status, f"{'; '.join(found)} | shifted input: program {'converges' if r1['prog']['converged'] else 'fails'}, " \
                       f"axtb {'converges' if r1['ax']['converged'] else 'fails'}"
    met1 = metrics(r1["ax"], r1["prog"])
    rest = issues(version, met1, gradient)
    own = metrics(r1["ax"], r0["ax"])
    note = f"{'; '.join(found)} | shifted: {'; '.join(rest) or 'agree'} | axtb's own change: {describe(own)}"
    if gradient and rest and all(s.startswith("dG") for s in rest) and own.get("dG", 0) <= 0.1 * met1["dG"]:
        # g-xTB 2.0.1 is rotation invariant (energies to ~1e-13 Eh), so a rotation is a round-off
        # probe as well; it also tells the program's orientation-dependent gradient apart
        r2 = measure(version, m, wd / "rot", ROT)
        if r2["prog"]["converged"] and r2["ax"]["converged"]:
            met2 = metrics(r2["ax"], r2["prog"])
            own2 = metrics(r2["ax"], r0["ax"])
            note += f" | rotated: {'; '.join(issues(version, met2, True)) or 'agree'}, axtb's own change dG {own2['dG']:.1e}"
            if not issues(version, met2, True) and own2["dG"] <= TOL_G:
                return "program-gradient", note
            if own2["dG"] >= 0.1 * met0["dG"]:
                return "rounding-sensitive", note
    if not rest:
        return "rounding-sensitive", note
    t0 = max((abs(v) for v in met0["dterms"].values()), default=0.0)
    t1 = max((abs(v) for v in own["dterms"].values()), default=0.0)
    moved = own["iterations"][0] != own["iterations"][1] or any(
        o >= 0.1 * s and s > tol for s, o, tol in ((abs(met0["dE"]), abs(own["dE"]), TOL_E), (t0, t1, TOL_T[version]),
                                                   (met0.get("dG", 0.0), own.get("dG", 0.0), TOL_G)))
    return ("rounding-sensitive" if moved else "real-difference"), note


def compare(version: str, m, wd: Path, pool, fd: bool) -> dict:
    r0 = measure(version, m, wd)
    p, a = r0["prog"], r0["ax"]
    row = {"program": {k: p[k] for k in ("energy", "iterations", "converged", "error")},
           "axtb": {k: a[k] for k in ("energy", "iterations", "error")}}
    method = "gxtb-v2.0.1" if version == "2.0.1" else "gxtb-v1.1"
    axd = run_axtb_file(m, wd / "axd", method, "axtb")
    row["axtb_default_conventions"] = {"energy": axd.get("energy"), "iterations": axd.get("iterations"),
                                       "error": axd.get("error")}
    if version == "1.1" and m["Z"] in V11_MISSING:
        how = "axtb refuses" if a["error"] else "axtb runs"
        prog = "the program fails" if not p["converged"] else "the program runs with zero parameters"
        row["status"], row["note"] = "unparametrized", f"no v1.1 parameters for Z = {m['Z']}: {how}, {prog}"
        return row
    if not p["converged"] and not a["converged"]:
        row["status"], row["note"] = "both-fail", f"program: {p['error']}; axtb: {a['error']}"
        return row
    if p["converged"] and a["converged"]:
        met = metrics(a, p)
        row.update({k: met[k] for k in ("dE", "iterations", "dterms")})
        if version == "2.0.1":
            row["dG"] = met["dG"]
        if axd.get("energy") is not None:
            row["dE_default"] = axd["energy"] - p["energy"]
    if version == "2.0.1":  # the program's tight thresholds (--acc 1e-4)
        progt = run_xtb2(m, wd / "progt", "--grad", "--acc", "0.0001")
        axt = run_axtb_file(m, wd / "axt", method, "gxtb", "--grad", "--acc", "0.0001", "--max-iter", "250")
        row["program_tight"] = {k: progt.get(k) for k in ("energy", "iterations", "converged", "error")}
        row["axtb_tight"] = {"energy": axt.get("energy"), "iterations": axt.get("iterations"), "error": axt.get("error")}
        if progt["converged"] and "error" not in axt:
            row["dE_tight"] = axt["energy"] - progt["energy"]
            row["dG_tight"] = maxdiff(axt["gradient"], progt["gradient"])
            row["iterations_tight"] = [axt["iterations"], progt["iterations"]]
        else:
            row["tight_failure"] = ("both" if not progt["converged"] and "error" in axt
                                    else "program" if not progt["converged"] else "axtb")
        # tight mismatches: the same runs on the shifted molecule (round-off only)
        path = row.get("tight_failure") in ("program", "axtb") or (
            "iterations_tight" in row and row["iterations_tight"][0] != row["iterations_tight"][1])
        if not path and row.get("dG_tight", 0) > TOL_G:
            row["tight_status"] = "gradient"  # resolved with the default-threshold status below
        if path:
            ms, _ = transformed(m, SHIFT)
            ps = run_xtb2(ms, wd / "progt-shift", "--acc", "0.0001")
            axs = run_axtb_file(ms, wd / "axt-shift", method, "gxtb", "--acc", "0.0001", "--max-iter", "250")
            own_p = (ps["converged"], ps.get("iterations")) != (progt["converged"], progt.get("iterations"))
            own_a = ("error" not in axs, axs.get("iterations")) != ("error" not in axt, axt.get("iterations"))
            row["tight_status"] = "rounding-sensitive" if own_p or own_a else "real-difference"
            row["tight_note"] = (f"shifted input, tight: program {'converges in ' + str(ps.get('iterations')) if ps['converged'] else 'fails'}"
                                 f" (was {progt.get('iterations') if progt['converged'] else 'failing'}), axtb "
                                 f"{'converges in ' + str(axs.get('iterations')) if 'error' not in axs else 'fails'}"
                                 f" (was {axt.get('iterations') if 'error' not in axt else 'failing'})")
    else:
        if p["converged"]:
            pg = run_gxtb11(m, wd / "progg", "-grad", "-symthr", "0")
            if pg.get("gradient") and a["gradient"] is not None:
                row["dG_program"] = maxdiff(a["gradient"], pg["gradient"])
        if a["converged"] and fd:
            for conv in ("gxtb", "axtb"):
                row[f"fd_{conv}"] = fd_check(m, method, conv, pool)
    key = (version, m["id"])
    if p["converged"] != a["converged"]:
        found = "only " + ("the program" if p["converged"] else "axtb") + " converges"
        r1 = measure(version, m, wd / "shift", SHIFT)
        same = r1["prog"]["converged"] == r1["ax"]["converged"]
        row["status"] = "rounding-sensitive" if same else "real-difference"
        row["note"] = found + (f" | shifted: both {'converge' if r1['ax']['converged'] else 'fail'}" if same else "")
    else:
        found = issues(version, met, version == "2.0.1")
        if not found:
            row["status"], row["note"] = "ok", ""
        else:
            row["status"], row["note"] = diagnose(version, m, wd, r0, met, found)
    for conv in ("gxtb", "axtb"):
        f = row.get(f"fd_{conv}", {})
        if "error" in f or (f.get("max_dgrad", 0) > TOL_G and "step_Eh" not in f):
            row["fd_note"] = f"FD ({conv}): " + (f["error"] if "error" in f else f"{f['max_dgrad']:.1e}")
    if key in KNOWN:
        row["status"], row["note"] = KNOWN[key][0], KNOWN[key][1] + (f" ({row['note']})" if row.get("note") else "")
    if key in KNOWN_TIGHT and "tight_status" in row:
        row["tight_status"], row["tight_note"] = KNOWN_TIGHT[key][0], KNOWN_TIGHT[key][1] + f" ({row.get('tight_note', '')})"
    if row.get("tight_status") == "gradient":  # same iterations, only the tight gradients differ
        same = row["status"] in ("rounding-sensitive", "program-gradient")
        row["tight_status"] = row["status"] if same else "real-difference"
        row["tight_note"] = (f"tight gradients differ by {row['dG_tight']:.1e} with the same iterations"
                             + (", as at the default thresholds" if same else ""))
    return row


def worker(version, m, scratch, pool, fd):
    wd = scratch / version / m["id"]
    row = compare(version, m, wd, pool, fd)
    head = {k: m[k] for k in ("id", "element", "Z", "label", "kind", "charge", "uhf")}
    head["natoms"] = len(m["numbers"])
    return {**head, "version": version, **row}


def report_table(rows):
    """One compact row per molecule and version for the report."""
    out = []
    for r in rows:
        fd = r.get("fd_gxtb", {})
        dg = r.get("dG") if r["version"] == "2.0.1" else fd.get("max_dgrad")
        out.append({"version": r["version"], "Z": r["Z"], "element": r["element"], "molecule": r["label"],
                    "kind": r["kind"], "charge": r["charge"], "uhf": r["uhf"], "dE": r.get("dE"),
                    "iterations": r.get("iterations"), "dG": dg, "fd_energy_step": "step_Eh" in fd,
                    "status": r["status"], "note": r["note"].split(" | ")[0]})
    return out


def summarize(rows):
    out = {}
    for v in sorted({r["version"] for r in rows}):
        rs = [r for r in rows if r["version"] == v]
        both = [r for r in rs if "dE" in r]
        st = {}
        for r in rs:
            st[r["status"]] = st.get(r["status"], 0) + 1
        out[v] = {
            "molecules": len(rs), "elements": len({r["Z"] for r in rs}),
            "status": st,
            "compared": len(both),
            "max_abs_dE_ok": max((abs(r["dE"]) for r in both if r["status"] == "ok"), default=None),
            "max_abs_dE": max((abs(r["dE"]) for r in both), default=None),
            "iteration_mismatches": [r["id"] for r in both if r["iterations"][0] != r["iterations"][1]],
            "max_dterm": max((max((abs(x) for x in r["dterms"].values()), default=0) for r in both), default=None),
        }
        if v == "2.0.1":
            out[v]["max_dG"] = max((r["dG"] for r in both if r["status"] == "ok"), default=None)
            out[v]["max_dG_tight"] = max((r["dG_tight"] for r in rs if "dG_tight" in r and r["status"] == "ok"
                                          and "tight_status" not in r), default=None)
            out[v]["tight_mismatches"] = {r["id"]: r["tight_status"] for r in rs if "tight_status" in r}
        else:
            for conv in ("gxtb", "axtb"):
                fds = [(r[f"fd_{conv}"], r["id"]) for r in rs if "max_dgrad" in r.get(f"fd_{conv}", {})]
                out[v][f"max_dG_fd_{conv}"] = max((f["max_dgrad"] for f, _ in fds if "step_Eh" not in f), default=None)
                out[v][f"max_dG_fd_{conv}_by_molecule"] = sorted((f["max_dgrad"], i) for f, i in fds
                                                                 if "step_Eh" not in f)[-4:]
                out[v][f"fd_{conv}_energy_steps"] = {i: f["step_Eh"] for f, i in fds if "step_Eh" in f}
                out[v][f"fd_{conv}_failed"] = [r["id"] for r in rs if "error" in r.get(f"fd_{conv}", {})]
            out[v]["max_dG_program_numerical"] = max((r["dG_program"] for r in rs if "dG_program" in r), default=None)
    return out


