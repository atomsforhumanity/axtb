def _cone(n, theta_deg, r, phase_deg=0.0, axis=1.0):
    """n points at distance r around the z axis at polar angle theta (from +z if axis > 0,
    from -z if axis < 0), evenly spaced in azimuth starting at `phase_deg`."""
    t = math.radians(theta_deg)
    out = []
    for k in range(n):
        p = math.radians(phase_deg + 360.0 * k / n)
        out.append([r * math.sin(t) * math.cos(p), r * math.sin(t) * math.sin(p), axis * r * math.cos(t)])
    return np.array(out)


def _mol(syms, pos_aa):
    return S.finish(syms, np.asarray(pos_aa, dtype=float))


def diatomic(a, b, r):
    return _mol([a, b], [[0, 0, 0], [0, 0, r]])


def water(r, angle=104.5):
    h = math.radians(angle / 2)
    return _mol(["O", "H", "H"], [[0, 0, 0], [r * math.sin(h), 0, r * math.cos(h)], [-r * math.sin(h), 0, r * math.cos(h)]])


def ethane(rcc, rch=1.09, hcc=111.0):
    c1 = np.array([0.0, 0.0, 0.0])
    c2 = np.array([0.0, 0.0, rcc])
    h1 = _cone(3, 180.0 - hcc, rch, 0.0, axis=-1.0)
    h2 = _cone(3, 180.0 - hcc, rch, 60.0) + c2
    return _mol(["C", "C"] + ["H"] * 6, np.vstack([c1, c2, h1, h2]))


def sn2_image(t, r_react=1.80, r_far=3.20, rch=1.08, theta=71.5):
    """Cl- + CH3Cl -> ClCH3 + Cl-, linear synchronous path at t in [0, 1]: C-Cl(a) from
    1.80 to 3.20 Å, C-Cl(b) from 3.20 to 1.80 Å, the methyl umbrella inverting."""
    da = r_react + t * (r_far - r_react)
    db = r_far + t * (r_react - r_far)
    th = theta + t * (180.0 - 2 * theta)
    hs = _cone(3, th, rch)
    return _mol(["C", "Cl", "Cl", "H", "H", "H"], np.vstack([[0, 0, 0], [0, 0, -da], [0, 0, db], hs]))


def proton_transfer_image(t, rnn=3.10):
    """H3N + HCl -> NH4+ Cl- at fixed N...Cl = 3.10 Å: the proton moves from Cl-H 1.30 Å
    (t = 0) to N-H 1.03 Å (t = 1)."""
    zh = (rnn - 1.30) + t * (1.03 - (rnn - 1.30))
    hs = _cone(3, 70.5, 1.02, axis=-1.0)
    return _mol(["N", "Cl", "H", "H", "H", "H"], np.vstack([[0, 0, 0], [0, 0, rnn], [0, 0, zh], hs]))


def h_transfer_image(t, rco=2.60):
    """CH4 + OH -> CH3 + H2O at fixed C...O = 2.60 Å (doublet): the H moves from C-H 1.09 Å
    (t = 0) to O-H 0.98 Å (t = 1) while the methyl flattens."""
    zh = 1.09 + t * ((rco - 0.98) - 1.09)
    hs = _cone(3, 70.5 + t * 19.5, 1.09, axis=-1.0)
    a = math.radians(104.0)  # H-O...H angle of the hydroxyl hydrogen
    ho = [0.97 * math.sin(a), 0.0, rco - 0.97 * math.cos(a)]
    return _mol(["C", "O", "H", "H", "H", "H", "H"], np.vstack([[0, 0, 0], [0, 0, rco], [0, 0, zh], hs, [ho]]))


def mn2o(rmo=1.78, angle=120.0):
    h = math.radians(angle / 2)
    return _mol(["O", "Mn", "Mn"], [[0, 0, 0], [rmo * math.sin(h), 0, rmo * math.cos(h)], [-rmo * math.sin(h), 0, rmo * math.cos(h)]])


def cyclobutadiene_square(rcc=1.45, rch=1.08):
    s = rcc / math.sqrt(2.0)
    c = np.array([[s, 0, 0], [0, s, 0], [-s, 0, 0], [0, -s, 0]])
    h = c * (1.0 + rch / s)
    return _mol(["C"] * 4 + ["H"] * 4, np.vstack([c, h]))


def h4_square(r=1.20):
    s = r / 2
    return _mol(["H"] * 4, [[s, s, 0], [-s, s, 0], [-s, -s, 0], [s, -s, 0]])


def h_chain(n=6, r=1.60):
    return _mol(["H"] * n, [[0, 0, r * k] for k in range(n)])


def p_benzyne(rcc=1.39, rch=1.08):
    R = rcc
    c = np.array([[R * math.cos(math.radians(60 * k)), R * math.sin(math.radians(60 * k)), 0.0] for k in range(6)])
    h = np.array([c[k] * (1.0 + rch / R) for k in (1, 2, 4, 5)])
    return _mol(["C"] * 6 + ["H"] * 4, np.vstack([c, h]))


def ethylene_twisted():
    return S.molecule("ethylene_twisted")


SCAN_R = (2.0, 2.5, 3.0, 3.5, 4.0)
SN2_T = tuple(k / 6 for k in range(7))
PT_T = tuple(k / 5 for k in range(6))


def structures():
    """name -> (builder, charge, uhf, category, label)."""
    out = {}
    for r in SCAN_R:
        out[f"scan-N2-{r:.1f}"] = (lambda r=r: diatomic("N", "N", r), 0, 0, "dissociation", f"N2 at {r} Å, singlet")
        out[f"scan-F2-{r:.1f}"] = (lambda r=r: diatomic("F", "F", r), 0, 0, "dissociation", f"F2 at {r} Å, singlet")
        out[f"scan-HF-{r:.1f}"] = (lambda r=r: diatomic("H", "F", r), 0, 0, "dissociation", f"HF at {r} Å, singlet")
        out[f"scan-H2O-{r:.1f}"] = (lambda r=r: water(r), 0, 0, "dissociation", f"H2O, both O-H at {r} Å, singlet")
        out[f"scan-C2H6-{r:.1f}"] = (lambda r=r: ethane(r), 0, 0, "dissociation", f"ethane, C-C at {r} Å, singlet")
