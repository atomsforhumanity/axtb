def run_axtb(case: dict, mixer: str, binary: str) -> dict:
    req = {"numbers": case["numbers"], "positions": case["positions"], "charge": float(case["charge"]),
           "uhf": case["uhf"], "accuracy": ACCURACY, "etemp": case["etemp"], "max_iter": MAX_ITER, "threads": 1,
           "conventions": "axtb"}
    if mixer != "default":
        req["mixer"] = mixer
    p = subprocess.run([binary, "--json"], input=json.dumps(req), capture_output=True, text=True, timeout=3600)
    if p.returncode == 0:
        r = json.loads(p.stdout)
        out = {"converged": True, "iterations": r["iterations"], "energy": r["energy"]}
        if mixer == "auto":
            out.update(mixer_used=r.get("mixer_used"), scf_attempts=r.get("scf_attempts"))
        return out
    err = (p.stderr + p.stdout).strip()
    m = re.search(r"SCF not converged in (\d+) iterations", err)
    if m:
        return {"converged": False, "iterations": int(m.group(1)), "energy": None, "error": err[-300:]}
    return {"converged": False, "iterations": None, "energy": None, "error": err[-300:]}


def run_xtb(case: dict) -> dict:
    scratch = Path(os.environ.get("AXTB_SCRATCH") or tempfile.gettempdir()) / "axtb-scf-hard"
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=scratch, prefix="xtb-") as d:
        d = Path(d)
        lines = ["$coord"] + [f"{x:24.16f} {y:24.16f} {z:24.16f} {S.SYMBOLS[n - 1].lower()}"
                              for n, (x, y, z) in zip(case["numbers"], case["positions"])]
        (d / "coord").write_text("\n".join(lines + ["$end", ""]))
        cmd = [XTB, "coord", "--gfn", "2", "--sp", "--acc", repr(ACCURACY), "--chrg", str(case["charge"]),
               "--uhf", str(case["uhf"]), "--etemp", repr(case["etemp"]), "--iterations", str(MAX_ITER)]
        env = dict(os.environ, OMP_NUM_THREADS="1", MKL_NUM_THREADS="1", OMP_STACKSIZE="1G")
        p = subprocess.run(cmd, cwd=d, capture_output=True, text=True, env=env, timeout=3600)
    out = p.stdout
    it = re.findall(r"convergence criteria satisfied after\s+(\d+)\s+iterations", out)
    en = re.findall(r"TOTAL ENERGY\s+(-?\d+\.\d+)", out)
    if it and p.returncode == 0:
        return {"converged": True, "iterations": int(it[-1]), "energy": float(en[-1])}
    err = [l.strip() for l in (out + p.stderr).splitlines() if "[ERROR]" in l or "not converge" in l.lower()]
    return {"converged": False, "iterations": MAX_ITER if any("converge" in e.lower() for e in err) else None,
            "energy": None, "error": " | ".join(err)[-300:] or f"rc {p.returncode}"}


def run_tblite(case: dict) -> dict:
    req = {k: case[k] for k in ("numbers", "positions", "charge", "uhf", "etemp")}
    p = subprocess.run([PYTHON, str(Path(__file__).resolve()), "--tblite-child"], input=json.dumps(req),
                       capture_output=True, text=True, timeout=3600,
                       env=dict(os.environ, OMP_NUM_THREADS="1", MKL_NUM_THREADS="1"))
    cycles = re.findall(r"^\s+(\d+)\s+-?\d+\.\d+\s+\S+\s+\S+\s*$", p.stdout, flags=re.M)
    res = [json.loads(l) for l in p.stdout.splitlines() if l.startswith("{")]
    if not res:
        return {"converged": False, "iterations": None, "energy": None,
                "error": f"tblite died (rc {p.returncode}): {p.stderr.strip()[-200:]}"}
    r = res[-1]
    n = int(cycles[-1]) if cycles else None
    if r["ok"]:
        return {"converged": True, "iterations": n, "energy": r["energy"]}
    return {"converged": False, "iterations": n, "energy": None, "error": r["error"][-300:]}


def _tblite_child():
    from tblite.interface import Calculator
    req = json.loads(sys.stdin.read())
    try:
        calc = Calculator("GFN2-xTB", np.asarray(req["numbers"]), np.asarray(req["positions"], dtype=float),
                          charge=float(req["charge"]), uhf=req["uhf"])
        calc.set("verbosity", 1)
        calc.set("accuracy", ACCURACY)
        calc.set("max-iter", MAX_ITER)
        calc.set("temperature", float(req["etemp"]) * KB_XTB)
        r = calc.singlepoint()
        res = {"ok": True, "energy": float(r.get("energy"))}
    except Exception as e:  # noqa: BLE001
        res = {"ok": False, "error": f"{type(e).__name__}: {e}"}
    sys.stdout.flush()
    print(json.dumps(res), flush=True)


def program_versions(binary: str) -> dict:
    v = {}
    try:
        out = subprocess.run([XTB, "--version"], capture_output=True, text=True).stdout
        m = re.search(r"xtb version (\S+)", out)
        v["xtb"] = m.group(1) if m else None
    except (OSError, TypeError):  # TypeError: no xtb (None)
        v["xtb"] = None
    try:
        out = subprocess.run([PYTHON, "-c", "import importlib.metadata as m; print(m.version('tblite'))"],
                             capture_output=True, text=True).stdout.strip()
        v["tblite"] = out or None
    except Exception:  # noqa: BLE001
        v["tblite"] = None
    if Path(binary) == ROOT / "target/release/axtb":
        try:
            git = ["git", "-C", str(ROOT)]
            commit = subprocess.run(git + ["rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
            dirty = subprocess.run(git + ["status", "--porcelain", "--untracked-files=no", "crates"],
                                   capture_output=True, text=True).stdout.strip()
            v["axtb"] = f"{commit}{'+local changes' if dirty else ''} (target/release/axtb)"
        except Exception:  # noqa: BLE001
            v["axtb"] = "target/release/axtb"
    else:
        v["axtb"] = "AXTB_BIN"
    cpu = platform.processor() or platform.machine()
    try:
        cpu = next(l.split(":", 1)[1].strip() for l in open("/proc/cpuinfo") if l.startswith("model name"))
    except (OSError, StopIteration):
        pass
    v["machine"] = f"{cpu}, {os.cpu_count()} threads"
    return v


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write-structures", action="store_true")
    ap.add_argument("--tblite-child", action="store_true", help=argparse.SUPPRESS)
    ap.add_argument("--programs", default="axtb,xtb,tblite")
    ap.add_argument("--mixers", default="broyden,diis,auto", help="axtb SCF mixers, comma-separated")
    ap.add_argument("--only", default=None)
    ap.add_argument("--jobs", type=int, default=os.cpu_count() // 2 or 1)
    ap.add_argument("--out", default=str(ROOT / "bench/results/scf_hard.json"))
    ap.add_argument("--merge", action="store_true", help="keep runs of other methods already in --out")
    args = ap.parse_args()
    if args.tblite_child:
        _tblite_child()
        return 0
    if args.write_structures:
        write_structures()
        return 0
    binary = os.environ.get("AXTB_BIN", str(ROOT / "target/release/axtb"))
    cs = [c for c in cases() if not args.only or args.only in c["id"]]
    progs = args.programs.split(",")
    if "xtb" in progs and not programs.note_skip("the xtb runs", programs.GXTB2):
        progs.remove("xtb")
    jobs = []
    for c in cs:
        if "axtb" in progs:
            for mx in args.mixers.split(","):
                jobs.append((c, f"axtb-{mx}", lambda c=c, mx=mx: run_axtb(c, mx, binary)))
        if "xtb" in progs:
            jobs.append((c, "xtb-6.7.1", lambda c=c: run_xtb(c)))
        if "tblite" in progs:
            jobs.append((c, "tblite-0.8.0", lambda c=c: run_tblite(c)))

    def work(job):
        c, method, fn = job
        return dict(case=c["id"], method=method, **fn())

    with ThreadPoolExecutor(args.jobs) as ex:
        runs = list(ex.map(work, jobs))
    out_path = Path(args.out)
    old = json.loads(out_path.read_text()) if args.merge and out_path.exists() else {}
    keep = [r for r in old.get("runs", []) if (r["case"], r["method"]) not in {(x["case"], x["method"]) for x in runs}]
    data = {
        "description": "GFN2-xTB SCF convergence on the hard-SCF set (tests/scf_hard_set.py)",
        "date": _dt.date.today().isoformat(),
        "settings": {"accuracy": ACCURACY, "max_iter": MAX_ITER, "threads": 1, "conventions": "axtb (default)"},
        "versions": program_versions(binary),
        "cases": [{k: c[k] for k in ("id", "structure", "category", "label", "charge", "uhf", "etemp")}
                  | {"natoms": len(c["numbers"])} for c in cases()],
        "runs": sorted(keep + runs, key=lambda r: (r["case"], r["method"])),
    }
    data["summary"] = summarize(data)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(dump_json(data))
    return 0


def dump_json(data: dict) -> str:
    """JSON with one case or run per line."""
    parts = []
    for k, v in data.items():
        if isinstance(v, list):
            body = ",\n".join("  " + json.dumps(x) for x in v)
            parts.append(f" {json.dumps(k)}: [\n{body}\n ]")
        else:
            parts.append(f" {json.dumps(k)}: {json.dumps(v)}")
    return "{\n" + ",\n".join(parts) + "\n}\n"


def summarize(data: dict) -> list[dict]:
    """Per method: converged/failed, and iterations over its own converged cases and over the
    cases every method converged (printed and returned for the JSON file)."""
    methods = sorted({r["method"] for r in data["runs"]})
    by = {(r["case"], r["method"]): r for r in data["runs"]}
    case_ids = sorted({r["case"] for r in data["runs"]})
    common = [c for c in case_ids if all((c, m) in by and by[(c, m)]["converged"] for m in methods)]
    print(f"{len(case_ids)} cases, {len(common)} converged by every method")
    print(f"{'method':16s} {'converged':>10s} {'failed':>7s} {'median it':>10s} {'mean it':>8s}"
          f" {'median/mean it, common':>24s}")
    out = []
    for m in methods:
        rs = [by[(c, m)] for c in case_ids if (c, m) in by]
        its = [r["iterations"] for r in rs if r["converged"]]
        cit = [by[(c, m)]["iterations"] for c in common]
        row = {"method": m, "converged": len(its), "failed": len(rs) - len(its),
               "median_iterations": float(np.median(its)) if its else None,
               "mean_iterations": float(np.mean(its)) if its else None,
               "common_cases": len(common), "common_median_iterations": float(np.median(cit)) if cit else None,
               "common_mean_iterations": float(np.mean(cit)) if cit else None}
        out.append(row)
        print(f"{m:16s} {row['converged']:10d} {row['failed']:7d} {row['median_iterations'] or float('nan'):10.1f} "
              f"{row['mean_iterations'] or float('nan'):8.1f} {row['common_median_iterations'] or float('nan'):14.1f}"
              f" / {row['common_mean_iterations'] or float('nan'):.1f}")
    return out


if __name__ == "__main__":
    sys.exit(main())
