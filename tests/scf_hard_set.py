#!/usr/bin/env python3
"""Hard-SCF test set: GFN2-xTB SCF convergence on systems where SCFs struggle, for axtb,
xtb 6.7.1 and tblite 0.8.0.

    python tests/scf_hard_set.py --write-structures      # (re)generate tests/scf_hard/*.xyz
    python tests/scf_hard_set.py [--programs axtb,xtb,tblite] [--mixers broyden,diis] [--merge]
                                 [--only SUBSTRING] [--jobs N] [--out bench/results/scf_hard.json]

Structures are generated by code (no research structures): dissociation scans of N2, F2,
HF, H2O and ethane (C-C) at 2-4 Å as singlets; reaction-path images (SN2 Cl- + CH3Cl,
proton transfer H3N + HCl, H-atom transfer CH4 + OH); metal clusters (Fe4, Cu5, Mn2O, ...);
small-gap molecules (twisted ethylene, square cyclobutadiene, C2, p-benzyne, Cr2, ...);
open-shell and charged systems and transition-metal complexes built with the reference
matrix's builders (`tests/reference_matrix/structures.py`), and two seeded random
molecules of the matrix that are hard for every program. Each structure is an XYZ file
in `tests/scf_hard/` (Ångström; the comment line holds charge and unpaired electrons); a
case is a structure at an electronic temperature (300 K, and 0 K for a subset).

Every program runs single-threaded with the same settings: SCF accuracy 1e-4 (xtb's
tightest), at most 250 iterations, the same bohr coordinates. Per case and program the
script records whether the SCF converged, the iteration count and the final energy:

* axtb: the release CLI (`target/release/axtb --json`, or AXTB_BIN), default conventions,
  one run per mixer in `--mixers`: `broyden` (tblite's modified Broyden mixing, the only
  mixer before DIIS and the mixer of the xtb and tblite conventions), `diis`, and `auto`
  (the default: Broyden, then DIIS from the initial guess with another 250 iterations if
  Broyden does not converge; `iterations` is that of the converging attempt, failures count
  both attempts, and `mixer_used`/`scf_attempts` record which mixer converged);
* xtb: `xtb coord --gfn 2 --sp` (OMP_NUM_THREADS=1) with xtb 6.7.1, the g-xTB 2.0.1 build
  (`$AXTB_GXTB2`, see tests/programs.py; skipped without it), converged when it prints
  "convergence criteria satisfied after N iterations";
* tblite: the Python package in a child process (verbosity 1, iterations from its table).

Results go to `--out` as JSON: `{"settings": ..., "cases": [...], "runs": [{"case",
"method", "converged", "iterations", "energy", ...}], "summary": [...]}`, with `method` one of
`axtb-<mixer>` (`broyden`, `diis`, `auto`), `xtb-6.7.1`, `tblite-0.8.0`. `--merge` keeps the runs of
other methods already in the file.
"""

